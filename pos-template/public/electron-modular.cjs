/**
 * Electron Main Process - Modular Architecture
 * Entry point for the Electron application with all IPC handlers
 */

const { app, BrowserWindow, ipcMain } = require('electron');
const path = require('path');
const fs = require('fs');

// Import managers and handlers
const ElectronAuthManager = require('../src/electron/ElectronAuthManager.cjs');
const ElectronDatabaseManager = require('../src/electron/ElectronDatabaseManager.cjs');
const ElectronLicenseManager = require('../src/electron/ElectronLicenseManager.cjs');
const ElectronWindowManager = require('../src/electron/ElectronWindowManager.cjs');

// Import IPC handlers
const { registerAuthHandlers } = require('../src/electron/handlers/ipc-auth-handlers.cjs');
const { registerDatabaseHandlers } = require('../src/electron/handlers/ipc-database-handlers.cjs');
const { registerLicenseHandlers } = require('../src/electron/handlers/ipc-license-handlers.cjs');
const { registerAppHandlers } = require('../src/electron/handlers/ipc-app-handlers.cjs');
const { registerSalesHandlers } = require('../src/electron/handlers/ipc-sales-handlers.cjs');
const { registerCustomerHandlers } = require('../src/electron/handlers/ipc-customer-handlers.cjs');
const { registerSupplierHandlers } = require('../src/electron/handlers/ipc-supplier-handlers.cjs');
const { registerKitchenHandlers } = require('../src/electron/handlers/ipc-kitchen-handlers.cjs');
const { registerServiceHandlers } = require('../src/electron/handlers/ipc-service-handlers.cjs');
const { registerBiExportHandlers } = require('../src/electron/handlers/ipc-bi-export-handler.cjs');
const { registerCaisseHandlers } = require('../src/electron/handlers/ipc-cash-register-handlers.cjs');
const { registerStockHandlers } = require('../src/electron/handlers/ipc-stock-handlers.cjs');

// Global references
let mainWindow = null;
let authManager = null;
let databaseManager = null;
let licenseManager = null;
let windowManager = null;

// Determine if running in development or production
const isDev = !app.isPackaged;
const VITE_DEV_SERVER_URL = 'http://localhost:5173';

// Cached app configuration (theme, business name, modules, etc.)
let cachedAppConfig = null;

/**
 * Load application configuration (app-config.json) generated by the admin panel.
 *
 * In development: read from public/app-config.json
 * In production: read from dist/app-config.json inside app.asar
 */
function loadAppConfig() {
  try {
    if (cachedAppConfig) {
      return cachedAppConfig;
    }

    let configPath;
    let fallbackPath;

    if (isDev) {
      // When running `npm run electron-dev`, Vite serves assets,
      // but we also keep a copy in public/ for direct access.
      // NOTE: __dirname is already the project's `public/` folder.
      configPath = path.join(__dirname, 'app-config.json');
      // Fallback for dev: try src/config/app-config.json
      fallbackPath = path.join(__dirname, '..', 'src', 'config', 'app-config.json');
    } else {
      // In the packaged app, dist/ is inside app.asar
      // (electron-builder includes dist/**/* in the asar bundle)
      configPath = path.join(app.getAppPath(), 'dist', 'app-config.json');
      // Fallback: check if resources/config.json has database name info
      fallbackPath = path.join(path.dirname(app.getPath('exe')), 'resources', 'config.json');
    }

    console.log('⚙️ Loading app configuration from primary path:', configPath);

    if (!fs.existsSync(configPath)) {
      console.warn('⚠️ Primary config not found at:', configPath);
      console.log('📁 Trying fallback path:', fallbackPath);
      
      if (fs.existsSync(fallbackPath)) {
        configPath = fallbackPath;
        console.log('✅ Using fallback path:', fallbackPath);
      } else {
        console.warn('⚠️ app-config.json not found at any path');
        console.log('📂 Available paths checked:');
        console.log('  - Primary:', configPath);
        console.log('  - Fallback:', fallbackPath);
        return null;
      }
    }

    const raw = fs.readFileSync(configPath, 'utf8');
    cachedAppConfig = JSON.parse(raw);

    console.log('═══════════════════════════════════════════════════════════');
    console.log('✅ App configuration loaded successfully');
    console.log('📊 Database filename:', cachedAppConfig?.database?.filename);
    console.log('📝 Business name:', cachedAppConfig?.theme?.businessName);
    console.log('📦 Modules:', cachedAppConfig?.modules?.map(m => ({name: m.name, enabled: m.isEnabled})));
    console.log('📦 Module count:', cachedAppConfig?.modules?.length);
    console.log('🔍 Full config:', JSON.stringify(cachedAppConfig, null, 2));
    console.log('═══════════════════════════════════════════════════════════');
    
    return cachedAppConfig;
  } catch (error) {
    console.error('❌ Failed to load app configuration:', error);
    return null;
  }
}

/**
 * Initialize all managers
 * NOTE: This is async because we fully initialize the shared database
 * instance here so that IPC database handlers can use it immediately.
 */
async function initializeManagers() {
  console.log('Initializing managers...');
  
  try {
    // Initialize database manager first (and open the SQLite database)
    databaseManager = new ElectronDatabaseManager();
    await databaseManager.initializeDatabase();
    
    // Initialize other managers
    authManager = new ElectronAuthManager(databaseManager);
    licenseManager = new ElectronLicenseManager();
    windowManager = new ElectronWindowManager();
    
    console.log('All managers initialized successfully');
  } catch (error) {
    console.error('Failed to initialize managers:', error);
    throw error;
  }
}

/**
 * Register all IPC handlers
 */
function registerAllHandlers() {
  console.log('Registering IPC handlers...');
  
  try {
    // Helper passed to license handlers for USB detection
    const detectUSBDrives = () => licenseManager.detectUSBDrives();

    // Register handlers with their respective managers
    registerAuthHandlers(ipcMain, authManager, databaseManager);
    // Functional export expects a getter function returning the raw sqlite3 db instance
    registerDatabaseHandlers(() => databaseManager.getDatabase());
    registerLicenseHandlers(detectUSBDrives, loadAppConfig);
    registerAppHandlers(loadAppConfig, databaseManager);
    registerSalesHandlers(ipcMain, databaseManager);
    registerCustomerHandlers(ipcMain, databaseManager);
    registerSupplierHandlers(ipcMain, databaseManager);
    registerKitchenHandlers(ipcMain, databaseManager);
    registerServiceHandlers(ipcMain, databaseManager);
    registerBiExportHandlers(databaseManager);
    registerCaisseHandlers(ipcMain, databaseManager);
    registerStockHandlers(ipcMain, databaseManager);
    
    console.log('All IPC handlers registered successfully');
  } catch (error) {
    console.error('Failed to register IPC handlers:', error);
    throw error;
  }
}

/**
 * Create the main application window
 */
async function createWindow() {
  console.log('🚀 Creating main window...');
  
  // Determine correct paths based on environment
  // In development: preload.cjs is in public/
  // In production (packaged): preload.cjs is copied to dist/ inside app.asar
  let preloadPath;
  
  if (isDev) {
    // Development: look in public/ folder
    preloadPath = path.join(__dirname, 'preload.cjs');
  } else {
    // Production: preload is in dist/ folder (inside app.asar)
    preloadPath = path.join(app.getAppPath(), 'dist', 'preload.cjs');
  }
  
  const indexPath = isDev
    ? VITE_DEV_SERVER_URL
    : path.join(app.getAppPath(), 'dist', 'index.html');
  
  console.log('🔍 Environment:', isDev ? 'Development' : 'Production');
  console.log('📁 __dirname:', __dirname);
  console.log('📂 App path:', app.getAppPath());
  console.log('📦 Resources path:', process.resourcesPath);
  console.log('🔐 Preload path:', preloadPath);
  console.log('🌐 Index path:', indexPath);
  console.log('✅ Preload exists:', fs.existsSync(preloadPath));
  
  // If preload doesn't exist, log detailed error
  if (!fs.existsSync(preloadPath)) {
    console.error('❌ PRELOAD NOT FOUND!');
    console.error('   Searched at:', preloadPath);
    console.error('   isDev:', isDev);
    const distPath = path.join(app.getAppPath(), 'dist');
    if (fs.existsSync(distPath)) {
      console.error('   dist/ contents:', fs.readdirSync(distPath));
    }
  }
  
  // Create window using WindowManager
  mainWindow = windowManager.createMainWindow({
    width: 1400,
    height: 900,
    minWidth: 1024,
    minHeight: 768,
    webPreferences: {
      preload: preloadPath,
      nodeIntegration: false,
      contextIsolation: true,
      sandbox: false
    }
  });

  // Load the app
  if (isDev) {
    await mainWindow.loadURL(indexPath);
    mainWindow.webContents.openDevTools();
  } else {
    await mainWindow.loadFile(indexPath);
  }

  // Handle window events
  mainWindow.on('closed', () => {
    mainWindow = null;
  });

  console.log('Main window created successfully');
}

/**
 * Application initialization
 */
app.whenReady().then(async () => {
  console.log('=== Electron App Ready ===');
  console.log('Mode:', isDev ? 'Development' : 'Production');
  console.log('App Path:', app.getAppPath());
  console.log('User Data:', app.getPath('userData'));
  console.log('(userData is automatically determined by package.json "name" field)');
  
  try {
    // Initialize all managers (including database)
    await initializeManagers();
    
    // Register IPC handlers
    registerAllHandlers();
    
    // Create main window
    await createWindow();
    
    console.log('=== App Initialization Complete ===');
  } catch (error) {
    console.error('=== Fatal Error During Initialization ===');
    console.error(error);
    app.quit();
  }
});

/**
 * Handle application activation (macOS)
 */
app.on('activate', () => {
  if (BrowserWindow.getAllWindows().length === 0) {
    createWindow();
  }
});

/**
 * Handle all windows closed
 */
app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') {
    app.quit();
  }
});

/**
 * Cleanup before quit
 */
app.on('before-quit', async () => {
  console.log('App is quitting, cleaning up...');
  
  // Close database connections
  if (databaseManager) {
    try {
      await databaseManager.close();
      console.log('Database closed successfully');
    } catch (error) {
      console.error('Error closing database:', error);
    }
  }
});

/**
 * Handle uncaught exceptions
 */
process.on('uncaughtException', (error) => {
  console.error('Uncaught Exception:', error);
});

process.on('unhandledRejection', (reason, promise) => {
  console.error('Unhandled Rejection at:', promise, 'reason:', reason);
});

console.log('Electron main process loaded');
